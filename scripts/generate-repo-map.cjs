'use strict';
// Regenerates candidate ownership index from actual committed repository source.
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
function list(dir){const full=path.join(ROOT,dir);if(!fs.existsSync(full))return [];return fs.readdirSync(full,{withFileTypes:true}).flatMap(e=>{const p=path.posix.join(dir,e.name);return e.isDirectory()?list(p):[p]}).sort();}
function read(p){return fs.readFileSync(path.join(ROOT,p),'utf8');}
function createIndex(paths,routeSource,repoSources) {
  const agentPaths=paths.filter(p=>/^\.claude\/agents\/vsa-[^/]+\.md$/.test(p)).sort();
  const repoPaths=paths.filter(p=>/^src\/data\/repos\/[^/]+\.ts$/.test(p)&&!p.endsWith('.test.ts')).sort();
  const skills=paths.filter(p=>/^\.claude\/skills\/vsa-[^/]+\/SKILL\.md$/.test(p)).sort();
  const tokens=s=>[...new Set(String(s).replace(/([a-z])([A-Z])/g,'$1 $2').toLowerCase().split(/[^a-z0-9]+/).map(s=>s.length>3&&s.endsWith('s')?s.slice(0,-1):s).filter(s=>s.length>2&&!['vsa','system','guardian','workflow','src','data','repos','page','admin','module','for','the','with','and','test','file','component'].includes(s)))];
  const components=new Map();
  const lazy=[...routeSource.matchAll(/\bconst\s+([a-zA-Z0-9_]+)\s*=\s*lazy\(/g)];
  lazy.forEach((match,i)=>{const part=routeSource.slice(match.index,lazy[i+1]?.index??routeSource.length);const imp=part.match(/import\(["']\.\.\/pages\/([^"']+)["']\)/);if(imp)components.set(match[1],`src/pages/${imp[1]}.tsx`);});
  const foundRoutes=[];
  for(const m of routeSource.matchAll(/<Route\b([\s\S]*?)\/>/g)){
    const path=m[1].match(/\bpath=["']([^"']+)["']/)?.[1];
    const component=m[1].match(/\belement=\{<([A-Za-z0-9_]+)/)?.[1];
    if(path&&component&&components.has(component))foundRoutes.push({path,page:components.get(component)});
  }
  const routes=[...new Map(foundRoutes.map(x=>[x.path,x])).values()].sort((a,b)=>a.path.localeCompare(b.path));
  const repositories=repoPaths.map(path=>{
    const src=repoSources[path]||'';
    return {path,tables:[...new Set([...src.matchAll(/\.from\(\s*['"]([^'"]+)['"]/g)].map(m=>m[1]))].sort(),rpcs:[...new Set([...src.matchAll(/\.rpc\(\s*['"]([^'"]+)['"]/g)].map(m=>m[1]))].sort()};
  });
  const domains=agentPaths.map(path=>{
    const agent=path.split('/').pop().replace(/\.md$/,'');
    const domain=agent.replace(/^vsa-/,'');
    const names=tokens(domain);
    const isMatch=v=>tokens(v).some(t=>names.includes(t));
    const ownedRepos=repositories.filter(r=>isMatch(r.path));
    const ownedRoutes=routes.filter(r=>isMatch(r.path)||isMatch(r.page));
    const matchedSkills=skills.filter(s=>isMatch(s.split('/')[2]));
    return {domain,owning_subagent:agent,owning_playbook:path,owning_skills:matchedSkills,
      protected_domain:/(points-attendance|house-system)/.test(domain),
      routes:ownedRoutes.map(r=>r.path),pages:[...new Set(ownedRoutes.map(r=>r.page))].sort(),
      repositories:ownedRepos.map(r=>r.path),tables:[...new Set(ownedRepos.flatMap(r=>r.tables))].sort(),
      rpcs:[...new Set(ownedRepos.flatMap(r=>r.rpcs))].sort()};
  }).sort((a,b)=>a.domain.localeCompare(b.domain));
  return {schema_version:1,notice:'Generated candidate ownership only. Match-by-name may miss owners or overmatch; verify AGENTS.md, owning playbooks, Graphify and source. Never treat this index as access control or a protected-domain edit grant.',
    generated_from:['src/routes/index.tsx','src/data/repos/','.claude/agents/','.claude/skills/'],routes,repositories,domains};
}
function renderDoc(map) {
  const lines=['# Generated repository ownership map','','> Generated by `npm run repo-map:generate`. Do not edit either generated file manually.','> Ownership is **candidate matching**, not architectural truth or authorization. Check `AGENTS.md`, the corresponding playbook, Graphify and actual code.','',
  `**Coverage:** ${map.routes.length} registered routes, ${map.repositories.length} repository modules, ${map.domains.length} agent playbooks.`,'',
  '| Candidate domain | Owning playbook | Protected domain? | Matched routes | Matched repositories |','| --- | --- | --- | --- | --- |'];
  for(const d of map.domains)lines.push(`| ${d.domain} | \`${d.owning_subagent}\` | ${d.protected_domain?'Yes':'Review source'} | ${d.routes.map(x=>`\`${x}\``).join(', ')||'—'} | ${d.repositories.map(x=>`\`${x.split('/').pop()}\``).join(', ')||'—'} |`);
  lines.push('','## How to use','','Run `npm run repo-map:generate` after edits to routes, repositories, ownership playbooks or skills, and commit both generated files. `npm run repo-map:check` and Jest reject stale output. The JSON also lists each module’s literal Supabase table/view and RPC references.','', 'This index is **not** the database access-control inventory. Check migrations and `docs/rls-verification-checklist.md` before changing sensitive code.','');
  return lines.join('\n');
}
const paths=[...list('.claude/agents'),...list('.claude/skills'),...list('src/data/repos')];
const sources=Object.fromEntries(paths.filter(p=>/^src\/data\/repos\/[^/]+\.ts$/.test(p)&&!p.endsWith('.test.ts')).map(p=>[p,read(p)]));
const result=createIndex(paths,read('src/routes/index.tsx'),sources);
const outputs={'docs/ai/repo-map.json':JSON.stringify(result,null,2)+'\n','docs/ai/repo-map.md':renderDoc(result)};
let stale=false;
for(const [name,content] of Object.entries(outputs)){
 const file=path.join(ROOT,name);
 if(process.argv.includes('--check')){if(!fs.existsSync(file)||read(name)!==content){console.error('Stale generated ownership index: '+name);stale=true;}}
 else {fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,content);console.log('Updated '+name);}
}
if(stale)process.exitCode=1;
